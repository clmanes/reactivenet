// Generates src/generated/SpectrumRegistry.res from Spectrum's Custom Elements
// Manifests.
//
// Written rather than hand-maintained because the surface is 92 components and 482
// attributes: hand-written bindings diverge from the library on the first minor
// version, and the manifest is the library's own description of itself.
//
// Run with `bun run spectrum:registry` after upgrading @spectrum-web-components.

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const packagesDir = root + "node_modules/@spectrum-web-components/";
const outputPath = root + "src/generated/SpectrumRegistry.res";

// Icon elements are generated in their own right — 1147 of them, all attribute-less
// wrappers around a glyph. They are reached through the `icon` component instead.
const ICON_PACKAGES = new Set(["icons-workflow", "icons-ui", "icons", "iconset"]);
// Infrastructure: no tag a document would ever write.
const INFRASTRUCTURE = new Set(["base", "shared", "styles", "reactive-controllers"]);

const escape = (value) => String(value).replace(/\\/g, "\\\\").replace(/"/g, '\\"');

// A union of string literals in the manifest — `'text' | 'value' | 'none'` — is the
// component telling us exactly which values it accepts. Anything else is free text.
const enumValues = (typeText) => {
  if (!typeText) return [];
  const literals = [...typeText.matchAll(/'([^']*)'/g)].map((m) => m[1]);
  return literals.length >= 2 ? literals : [];
};

const kindOf = (typeText) => {
  if (!typeText) return "Text";
  const text = typeText.replace(/\s|undefined|\|/g, "");
  if (text === "boolean") return "Flag";
  if (text === "number") return "Number";
  return enumValues(typeText).length > 0 ? "Choice" : "Text";
};

const components = [];

for (const pkg of readdirSync(packagesDir)) {
  if (ICON_PACKAGES.has(pkg) || INFRASTRUCTURE.has(pkg)) continue;
  const manifestPath = `${packagesDir}${pkg}/custom-elements.json`;
  if (!existsSync(manifestPath)) continue;

  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch {
    continue;
  }

  for (const module of manifest.modules ?? []) {
    for (const declaration of module.declarations ?? []) {
      if (!declaration.customElement || !declaration.tagName) continue;

      // Descriptions are patchy in the manifests — about 40% of attributes and only
      // a handful of components carry one — so consumers fall back to the type.
      const attributes = (declaration.attributes ?? []).map((attribute) => ({
        name: attribute.name,
        description: (attribute.description ?? "").split("\n")[0].trim(),
        kind: kindOf(attribute.type?.text),
        choices: enumValues(attribute.type?.text),
        fallback: attribute.default === undefined ? "" : String(attribute.default).replace(/^['"]|['"]$/g, ""),
      }));

      components.push({
        package: pkg,
        tag: declaration.tagName,
        // The directive name is the tag without Spectrum's prefix, which is what
        // keeps this vocabulary distinct from ReactiveNET's.
        directive: declaration.tagName.replace(/^sp-/, ""),
        description: (declaration.description ?? "").split("\n")[0].trim(),
        slots: (declaration.slots ?? []).map((slot) => slot.name ?? ""),
        attributes,
      });
    }
  }
}

components.sort((a, b) => a.directive.localeCompare(b.directive));

const seen = new Set();
const unique = components.filter((component) => {
  if (seen.has(component.directive)) return false;
  seen.add(component.directive);
  return true;
});

const renderAttribute = (attribute) => `      {
        name: "${escape(attribute.name)}",
        description: "${escape(attribute.description)}",
        kind: ${attribute.kind},
        choices: [${attribute.choices.map((c) => `"${escape(c)}"`).join(", ")}],
        fallback: "${escape(attribute.fallback)}",
      }`;

const renderComponent = (component) => `  {
    directive: "${escape(component.directive)}",
    description: "${escape(component.description)}",
    tag: "${escape(component.tag)}",
    package: "${escape(component.package)}",
    slots: [${component.slots.map((s) => `"${escape(s)}"`).join(", ")}],
    attributes: [
${component.attributes.map(renderAttribute).join(",\n")}
    ],
  }`;

const file = `// GENERATED by scripts/generate-spectrum-registry.mjs — do not edit.
//
// Source: the Custom Elements Manifests shipped by @spectrum-web-components.
// Regenerate with \`bun run spectrum:registry\` after upgrading the library.
//
// ${unique.length} components, ${unique.reduce((n, c) => n + c.attributes.length, 0)} attributes.

type kind =
  | Flag
  | Number
  | Choice
  | Text

type attribute = {
  name: string,
  /** From the manifest; empty when the library does not document it. */
  description: string,
  kind: kind,
  choices: array<string>,
  fallback: string,
}

type component = {
  directive: string,
  /** From the manifest; empty when the library does not document it. */
  description: string,
  tag: string,
  package: string,
  slots: array<string>,
  attributes: array<attribute>,
}

let all: array<component> = [
${unique.map(renderComponent).join(",\n")},
]
`;

mkdirSync(root + "src/generated", { recursive: true });
writeFileSync(outputPath, file);

console.log(
  `${unique.length} components, ${unique.reduce((n, c) => n + c.attributes.length, 0)} attributes -> src/generated/SpectrumRegistry.res`,
);
