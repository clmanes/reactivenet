// Generates the Spectrum workflow icon vocabulary and geometry.
//
//   src/generated/SpectrumIcons.res    — the names, for validating and offering them
//   src/generated/spectrum-icons.json  — viewBox and shapes, loaded on demand
//
// The elements themselves are not an option: 1096 custom elements are 4.3 MB of
// JavaScript, and a per-icon dynamic import either explodes the build into a thousand
// chunks or — with the import left unanalysed — resolves in dev and fails in the
// bundle, which is worse. Extracting the drawings gives one 840 KB chunk, loaded only
// once a document actually names an icon, the same policy the component bundle uses.
//
// The Spectrum 2 drawing wins where it exists, because the app runs
// `system="spectrum-two"`; the older set fills in the rest, exactly as the elements
// themselves choose between them.

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const source = root + "node_modules/@spectrum-web-components/icons-workflow/src/";

const extract = (directory) => {
  const icons = {};
  for (const file of readdirSync(source + directory)) {
    if (!file.endsWith(".js")) continue;
    const text = readFileSync(source + directory + "/" + file, "utf8");
    const viewBox = /viewBox="([^"]+)"/.exec(text);
    const body = /aria-label="\$\{[^}]*\}"\s*>([\s\S]*?)<\/svg>/.exec(text);
    if (!viewBox || !body) continue;
    const shapes = body[1].replace(/\s+/g, " ").trim();
    // A drawing with a template placeholder in it is not a static shape; skipping it
    // is better than emitting one that renders as literal `${...}`.
    if (shapes.includes("${")) continue;
    icons[file.replace(/\.js$/, "")] = [viewBox[1], shapes];
  }
  return icons;
};

const icons = { ...extract("icons"), ...extract("icons-s2") };

// The element name is the file name in kebab case: DataMapping -> data-mapping.
const kebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();

const byDirectiveName = {};
for (const [name, drawing] of Object.entries(icons)) byDirectiveName[kebab(name)] = drawing;

const names = Object.keys(byDirectiveName).sort();

mkdirSync(root + "src/generated", { recursive: true });
writeFileSync(
  root + "src/generated/SpectrumIcons.res",
  `// GENERATED by scripts/generate-spectrum-icons.mjs — do not edit.
//
// The names of the workflow icons an app may name. The drawings live beside this in
// spectrum-icons.json and are loaded only when a document uses one.
//
// ${names.length} icons.

let all: array<string> = [
${names.map((name) => `  "${name}",`).join("\n")}
]
`
);
writeFileSync(
  root + "src/generated/spectrum-icons.json",
  JSON.stringify(byDirectiveName)
);

console.log(
  `${names.length} icons -> src/generated/SpectrumIcons.res + spectrum-icons.json`
);
